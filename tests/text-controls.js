// 文字（变量 / 点击菜单）、控制分区、左上角浮动面板、导出附带面板
const { chromium } = require('playwright');
const path = require('path');
const assert = require('assert');
const out = process.argv[2] || '/tmp/claude-0/shots';
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 }, acceptDownloads: true });
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + e.stack));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('file://' + path.resolve(__dirname, '..', 'index.html'));
  await page.evaluate(() => localStorage.clear()); await page.reload();
  await page.evaluate(() => { SG.AIPrompt.execute(SG.app, [{ op: 'solid', shape: 'cube', a: 2 }, { op: 'labels', show: true }]); SG.app.fit(); });
  await page.waitForTimeout(150);
  const rect = await page.evaluate(() => { const r = document.getElementById('cv').getBoundingClientRect(); return [r.left, r.top]; });
  const scrOf = async (n) => { const p = await page.evaluate((n) => SG.app.cam.project(SG.app.S.get(n).v), n); return [p[0] + rect[0], p[1] + rect[1]]; };

  console.log('· 文字工具：跟随点 A，插入变量，上屏');
  await page.click('#toolbar .cat[title="文字"]');
  const A = await scrOf('A');
  await page.mouse.click(A[0], A[1]);
  await page.waitForSelector('.tx-area');
  await page.fill('.tx-area', '∠A1BD = ');
  await page.fill('.tx-pts', 'A1,B,D');
  await page.click('button:has-text("插入角度")');
  const prev = await page.textContent('.tx-preview');
  assert.ok(prev.includes('60°'), prev);
  await page.click('.tx-chk:has-text("添加到左上角面板") input');
  await page.click('#modal .foot button.primary');
  await page.waitForTimeout(200);
  const t = await page.evaluate(() => { const o = SG.app.S.objects.find((x) => x.def.kind === 'text'); return { at: o.def.at, text: o.def.text, hud: document.querySelector('#hud .hud-text').textContent }; });
  console.log('  ', JSON.stringify(t));
  assert.ok(t.text.includes('{ang:A1,B,D}') && t.hud === '∠A1BD = 60°');
  console.log('· 文字随图形变化');
  await page.evaluate(() => { const B = SG.app.S.get('B'); });
  await page.keyboard.press('Escape');

  console.log('· 点击图中文字 → 菜单');
  const lab = await page.evaluate(() => { const o = SG.app.S.objects.find((x) => x.def.kind === 'text'); return SG.app.dl.hits.labels.find((l) => l.id === o.id); });
  await page.mouse.click(lab.x + rect[0] + lab.w / 2, lab.y + rect[1] + lab.h / 2);
  await page.waitForSelector('.tx-menu');
  const menu = await page.$$eval('.tx-menu button', (bs) => bs.map((b) => b.textContent));
  assert.ok(menu.includes('编辑文字…') && menu.includes('从左上角面板移除'), menu.join(','));
  await page.click('.tx-menu button:has-text("编辑文字…")');
  await page.waitForSelector('.tx-area');
  await page.fill('.tx-area', '|AC1| = {len:A,C1}');
  await page.click('#modal .foot button.primary');
  await page.waitForTimeout(150);
  assert.strictEqual(await page.textContent('#hud .hud-text'), '|AC1| = 2√3');
  console.log('· 点的标签菜单：添加到左上角');
  const labA = await page.evaluate(() => SG.app.dl.hits.labels.find((l) => l.id === SG.app.S.get('C1').id));
  await page.mouse.click(labA.x + rect[0] + labA.w / 2, labA.y + rect[1] + labA.h / 2);
  await page.click('.tx-menu button:has-text("添加到左上角面板")');
  assert.strictEqual(await page.evaluate(() => SG.app.hud.items.length), 2);

  console.log('· 控制分区：新建滑动条并上屏');
  await page.click('#side .tabs button[data-tab="controls"]');
  await page.click('#pane-controls button:has-text("新建控件")');
  await page.waitForSelector('.ce-param');
  const opt = await page.evaluate(() => Array.from(document.querySelectorAll('.ce-param option')).find((o) => o.textContent.includes('棱长')).value);
  await page.selectOption('.ce-param', opt);
  await page.click('.tx-chk:has-text("上屏") input');
  await page.click('#modal .foot button.primary');
  await page.waitForTimeout(200);
  assert.strictEqual(await page.evaluate(() => SG.app.controls.length), 1);
  const hr = await page.locator('#hud input[type=range]').boundingBox();
  await page.mouse.click(hr.x + hr.width * 0.95, hr.y + hr.height / 2);
  await page.waitForTimeout(150);
  const a = await page.evaluate(() => SG.app.S.objects.find((o) => o.type === 'solid').def.params.a);
  console.log('   a =', a);
  assert.ok(a > 2.5, '拖动左上角滑动条应改变棱长');
  const txt = await page.textContent('#hud .hud-text');
  assert.ok(!txt.includes('2√3'), '文字中的变量应随之变化：' + txt);
  console.log('· 按钮控件（AI 设计格式）');
  await page.evaluate(() => SG.app.setControls(SG.app.controls.concat(SG.Controls.normalizeAI([{ type: 'button', label: '恢复棱长 2', actions: [{ do: 'set', target: 'ABCD-A1B1C1D1', key: 'a', value: 2 }, { do: 'text', text: '体对角线 {len:A,C1}' }] }]))));
  await page.click('#pane-controls .cw-button');
  await page.waitForTimeout(800);
  assert.strictEqual(await page.evaluate(() => SG.app.S.objects.find((o) => o.type === 'solid').def.params.a), 2);
  assert.ok((await page.textContent('#pane-controls .pp-msg')).includes('2√3'));
  console.log('· 面板拖动与折叠');
  const hh = await page.locator('#hud .hud-head').boundingBox();
  await page.mouse.move(hh.x + 20, hh.y + hh.height / 2); await page.mouse.down(); await page.mouse.move(hh.x + 220, hh.y + 120, { steps: 5 }); await page.mouse.up();
  const pos = await page.evaluate(() => [document.getElementById('hud').offsetLeft, document.getElementById('hud').offsetTop]);
  assert.ok(pos[0] > 150 && pos[1] > 120, '面板应被拖动：' + pos);
  await page.screenshot({ path: out + '/tc-hud.png' });
  console.log('· 导出附带面板');
  const ex = await page.evaluate(() => { const dl = SG.app.exportDL(); const b0 = SG.Backend.contentBox(dl); const b1 = SG.HUD.addToExport(SG.app, dl, b0); return { grew: b1.h > b0.h, texts: dl.labels.filter((l) => l.k === 'text').map((l) => l.parts.map((p) => p.t).join('')) }; });
  assert.ok(ex.grew && ex.texts.some((s) => s.includes('|AC1| = 2√3')), JSON.stringify(ex));
  await page.evaluate(() => { SG.app.view.exportHud = false; });
  const ex2 = await page.evaluate(() => { const dl = SG.app.exportDL(); const b0 = SG.Backend.contentBox(dl); const b1 = SG.HUD.addToExport(SG.app, dl, b0); return b1.h === b0.h; });
  assert.ok(ex2, '关闭后不附带');
  await page.evaluate(() => { SG.app.view.exportHud = true; });
  const [dl] = await Promise.all([page.waitForEvent('download'), page.evaluate(() => SG.app.exportPNG())]);
  await dl.saveAs(out + '/tc-export.png');
  console.log('· 刷新后保留');
  await page.waitForTimeout(600);
  await page.reload(); await page.waitForTimeout(300);
  assert.ok(await page.evaluate(() => SG.app.controls.length === 2 && SG.app.hud.items.length === 3 && !document.getElementById('hud').classList.contains('hidden')));
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors');
  if (errors.length) process.exit(1);
  console.log('text & controls test passed');
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });

// 视角控制器与触屏手势测试
const { chromium } = require('playwright');
const path = require('path');
const assert = require('assert');
const out = process.argv[2] || '/tmp/claude-0/shots';
const url = 'file://' + path.resolve(__dirname, '..', 'index.html');
const near = (a, b, eps, msg) => assert.ok(Math.abs(a - b) < (eps || 0.5), (msg || '') + ` 期望 ${b}，实际 ${a}`);
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const errors = [];
  // ---------------- 桌面
  const page = await browser.newPage({ viewport: { width: 1400, height: 850 } });
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(url);
  await page.evaluate(() => localStorage.clear()); await page.reload();
  await page.evaluate(() => { SG.AIPrompt.execute(SG.app, [{ op: 'solid', shape: 'cube', a: 2 }, { op: 'labels', show: true }]); SG.app.fit(); });
  await page.waitForTimeout(150);
  const cam = () => page.evaluate(() => ({ az: SG.app.cam.az, el: SG.app.cam.el, scale: SG.app.cam.scale, panX: SG.app.cam.panX, panY: SG.app.cam.panY, mode: SG.app.cam.mode, yaw: SG.app.cam.yaw }));
  const gizmoClick = async (name, sgn) => {
    const p = await page.evaluate(([n, s]) => { const vc = document.querySelector('.vc-gizmo'); const r = vc.getBoundingClientRect(); const ctl = SG.app._vc; const q = ctl.pts.find((p) => p.axis.name === n && p.sgn === s); return [r.left + q.x, r.top + q.y]; }, [name, sgn]);
    await page.mouse.click(p[0], p[1]); await page.waitForTimeout(80);
  };
  console.log('· 坐标轴指示器');
  await gizmoClick('y', 1);
  let c = await cam(); near(c.az, 90); near(c.el, 0);
  await gizmoClick('y', 1);
  c = await cam(); near(c.az, -90, 0.5, '再点一次应转到反面');
  await gizmoClick('z', 1);
  c = await cam(); near(c.el, 89.9);
  console.log('· 按钮');
  await page.evaluate(() => SG.app.setAngles(32, 18));
  await page.click('.vc-btns button[title^="图形向左转"]'); await page.waitForTimeout(50);
  c = await cam(); near(c.az, 47);
  await page.click('.vc-btns button[title^="图形向下翻"]'); await page.waitForTimeout(50);
  c = await cam(); near(c.el, 33);
  await page.click('.vc-btns button:has-text("转到背面")'); await page.waitForTimeout(50);
  c = await cam(); near(c.az, -133);
  console.log('· 摇杆向右推');
  const pad = await page.locator('.vc-pad').boundingBox();
  await page.mouse.move(pad.x + pad.width / 2, pad.y + pad.height / 2); await page.mouse.down();
  await page.mouse.move(pad.x + pad.width - 2, pad.y + pad.height / 2, { steps: 3 });
  await page.waitForTimeout(500); await page.mouse.up();
  const c2 = await cam(); assert.ok(c2.az < c.az - 20 || c2.az > 150, '摇杆向右推，水平角应减小：' + c.az + ' → ' + c2.az); near(c2.el, 33, 2, '只左右推时俯仰不变');
  console.log('· 连续往下推：可以翻过头顶，不会卡在 90°');
  await page.evaluate(() => SG.app.setAngles(32, 70));
  const holdDown = async (ms) => {
    await page.mouse.move(pad.x + pad.width / 2, pad.y + pad.height / 2); await page.mouse.down();
    await page.mouse.move(pad.x + pad.width / 2, pad.y + pad.height - 2, { steps: 3 });
    await page.waitForTimeout(ms); await page.mouse.up();
  };
  const elTrack = await page.evaluate(() => { window.__els = []; SG.app.on('camera', () => window.__els.push(SG.app.cam.el)); return true; });
  void elTrack;
  await holdDown(900);
  const els = await page.evaluate(() => window.__els);
  const maxEl = Math.max(...els), last = els[els.length - 1];
  console.log('  俯仰角', els[0].toFixed(1), '→ 最大', maxEl.toFixed(1), '→ 最后', last.toFixed(1));
  assert.ok(maxEl > 95 || last < 0, '应能越过 90° 继续翻转');
  // 画布上拖动同样不受限
  await page.evaluate(() => SG.app.setAngles(32, 80));
  await page.mouse.move(300, 300); await page.mouse.down(); await page.mouse.move(300, 380, { steps: 8 }); await page.mouse.up();
  c = await cam(); assert.ok(c.el > 95, '画布拖动也应能越过 90°：' + c.el);
  console.log('· 保持 z 轴朝上：限制在 89.9°');
  await page.evaluate(() => { SG.app.view.upright = true; SG.app.setAngles(32, 70); });
  await holdDown(900);
  c = await cam(); assert.ok(c.el <= 89.9 + 1e-9 && c.el > 85, '打开后应停在 89.9°：' + c.el);
  await page.evaluate(() => { SG.app.view.upright = false; SG.app.setAngles(32, 18); });

  console.log('· 高级设置');
  await page.click('.vc-adv summary');
  await page.fill('.vc-adv input[type=number] >> nth=0', '60'); await page.keyboard.press('Enter');
  await page.fill('.vc-adv input[type=number] >> nth=1', '-20'); await page.keyboard.press('Enter');
  await page.waitForTimeout(50);
  c = await cam(); near(c.az, 60); near(c.el, -20);
  await page.screenshot({ path: out + '/view-desktop.png' });
  console.log('· 视角基准面（倾斜的面）');
  const bres = await page.evaluate(() => {
    const app = SG.app, V = SG.V;
    app.S.clear();
    SG.AIPrompt.execute(app, [{ op: 'point', name: 'A', coord: [0, 0, 0] }, { op: 'point', name: 'B', coord: [2, 0, 1] }, { op: 'point', name: 'C', coord: [0, 2, 1] }, { op: 'polygon', points: 'ABC' }]);
    app.setAngles(32, 18); app.fit();
    const poly = app.S.objects.find((o) => o.type === 'polygon');
    const F0 = app.cam.F.slice();
    app.setViewBase(poly.id);
    const jump = V.dist(F0, app.cam.F);
    const n = app.cam.base.n;
    const d0 = V.dot(app.cam.F, n);
    app.rotateView(40, 0); app.rotateView(-100, 0);
    const d1 = V.dot(app.cam.F, n);
    app.setAngles(app.cam.az, 18);
    const flat = V.dot(app.cam.F, n);
    app.setAngles(app.cam.az, 89.9);
    const facing = V.dot(app.cam.F, n);
    return { jump, d0, d1, flat, facing, nz: n };
  });
  await page.waitForTimeout(100);
  bres.label = await page.evaluate(() => document.querySelector('.vc-base-sel').selectedOptions[0].textContent);
  console.log('  ', JSON.stringify(bres));
  near(bres.jump, 0, 1e-9, '切换基准面时画面不应跳动');
  near(bres.d1, bres.d0, 1e-9, '左右转时与基准面的夹角不变');
  assert.ok(bres.d0 > 0, '当前看到的一侧应作为基准面的上方');
  near(bres.flat, Math.sin(18 * Math.PI / 180), 1e-9, '放平');
  near(bres.facing, 1, 1e-5, '正对');
  assert.ok(bres.label.includes('ABC'));
  await page.screenshot({ path: out + '/view-base.png' });
  await page.selectOption('.vc-base-sel', 'xy');
  near(await page.evaluate(() => SG.app.cam.base === null ? 1 : 0), 1, 0);

  console.log('· 面板收起');
  await page.click('#btnPanel'); await page.waitForTimeout(100);
  assert.ok(await page.evaluate(() => document.body.classList.contains('side-hidden')));
  await page.click('#btnPanel');
  await page.close();

  // ---------------- 平板（触屏）
  const ctx = await browser.newContext({ viewport: { width: 820, height: 1100 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
  const tp = await ctx.newPage();
  tp.on('pageerror', (e) => errors.push(e.message));
  await tp.goto(url);
  await tp.evaluate(() => { localStorage.clear(); }); await tp.reload();
  await tp.evaluate(() => { SG.AIPrompt.execute(SG.app, [{ op: 'solid', shape: 'cube', a: 2 }, { op: 'labels', show: true }]); SG.app.fit(); });
  await tp.waitForTimeout(200);
  assert.ok(await tp.evaluate(() => document.body.classList.contains('side-hidden')), '窄屏默认收起右侧面板');
  const tcam = () => tp.evaluate(() => ({ az: SG.app.cam.az, el: SG.app.cam.el, scale: SG.app.cam.scale, panX: SG.app.cam.panX, panY: SG.app.cam.panY }));
  const cdp = await ctx.newCDPSession(tp);
  const touch = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map(([x, y], i) => ({ x, y, id: i })) });
  console.log('· 双指捏合放大');
  let t0 = await tcam();
  await touch('touchStart', [[350, 500], [450, 500]]);
  for (let i = 1; i <= 8; i++) await touch('touchMove', [[350 - i * 10, 500], [450 + i * 10, 500]]);
  await touch('touchEnd', []);
  await tp.waitForTimeout(100);
  let t1 = await tcam();
  console.log('  scale', t0.scale.toFixed(1), '→', t1.scale.toFixed(1), ' az', t0.az, '→', t1.az);
  near(t1.scale / t0.scale, 260 / 100, 0.02, '缩放倍数应等于两指距离之比');
  near(t1.az, t0.az, 1e-9, '双指时不应旋转');
  console.log('· 双指平移');
  await touch('touchStart', [[300, 600], [400, 600]]);
  for (let i = 1; i <= 5; i++) await touch('touchMove', [[300 + i * 12, 600 + i * 8], [400 + i * 12, 600 + i * 8]]);
  await touch('touchEnd', []);
  await tp.waitForTimeout(100);
  const t2 = await tcam();
  near(t2.panX - t1.panX, 60, 1); near(t2.panY - t1.panY, 40, 1); near(t2.scale, t1.scale, 1e-6);
  console.log('· 单指旋转（触屏默认锁定方向）');
  assert.ok(await tp.evaluate(() => SG.app.rotLockOn()), '触屏应默认开启方向锁定');
  await touch('touchStart', [[200, 300]]);
  for (let i = 1; i <= 8; i++) await touch('touchMove', [[200 + i * 15, 300 + i * 4]]);
  await touch('touchEnd', []);
  await tp.waitForTimeout(100);
  const t3 = await tcam();
  assert.ok(Math.abs(t3.az - t2.az) > 10, '应水平转动'); near(t3.el, t2.el, 1e-9, '横向滑动时俯仰不变');
  await tp.screenshot({ path: out + '/view-tablet.png' });
  console.log('· 打开面板（抽屉）');
  await tp.click('#btnPanel'); await tp.waitForTimeout(100);
  await tp.screenshot({ path: out + '/view-tablet-panel.png' });
  await tp.click('#side .side-close'); await tp.waitForTimeout(50);
  assert.ok(await tp.evaluate(() => document.body.classList.contains('side-hidden')));
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors');
  if (errors.length) process.exit(1);
  console.log('view test passed');
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
